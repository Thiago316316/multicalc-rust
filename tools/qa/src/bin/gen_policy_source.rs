//! Writes the learned MLP policy out as Rust source for the on-target smoke run, so the
//! bare-metal side never reads a fixture file.
//!
//! Run `cargo run -p multicalc-qa --bin gen_policy_source`. The output is deterministic, so CI
//! regenerates it and diffs against the committed file.

use std::fmt::Write as _;
use std::path::Path;

use multicalc_qa::load::load_dir;

const CASE: &str = "policy_22x64x64x4";

/// Bit patterns per emitted line. The array is 5,892 entries long, so one per line would run to
/// six thousand; five keeps every line inside a hundred columns and the file under twelve.
const PER_LINE: usize = 5;

const HEADER: &str = "// GENERATED by `cargo run -p multicalc-qa --bin gen_policy_source`. Do not edit.\n\
     // Source: tools/qa/fixtures/mlp/policy_22x64x64x4.json, the `parameters` export.\n\
     // Left unformatted: this file's shape comes from the generator, and rustfmt would\n\
     // reflow the literals so a regenerate-and-diff check could never come out clean.\n\
     #![cfg_attr(rustfmt, rustfmt::skip)]\n\
     #![allow(clippy::unreadable_literal)]\n\
     #![allow(dead_code)]\n\n\
     /// Spells one `f32` by its bits, short enough to fit five entries on a line.\n\
     const fn bits(pattern: u32) -> f32 { f32::from_bits(pattern) }\n\n";

const DOC: &str = "\
/// The `mlp/policy_22x64x64x4` fixture's parameters in single precision: each layer's weights\n\
/// row-major, then its biases, in the order they are applied.\n\
///\n\
/// A `static`, not a `const`. A `const` is inlined wherever it is named, so borrowing one would\n\
/// cost a 23 KB copy in RAM; a `static` has an address in flash to borrow in place.\n";

fn main() {
    let fixtures = load_dir("mlp");
    let policy = fixtures
        .iter()
        .find(|fixture| fixture.case == CASE)
        .unwrap_or_else(|| unreachable!("fixture case {CASE:?} not found"));
    let parameters = policy.inputs["parameters"].as_vector();

    let mut out = String::from(HEADER);
    out.push_str(DOC);
    let _ = writeln!(
        out,
        "pub static POLICY_PARAMETERS: [f32; {}] = [",
        parameters.len()
    );
    for line in parameters.chunks(PER_LINE) {
        out.push_str("   ");
        for &value in line {
            // The fixture holds f64. Narrowing here rather than on target is the point: the chip
            // reads finished f32, and never spends RAM on a copy it converts into.
            let _ = write!(out, " bits(0x{:08x}),", (value as f32).to_bits());
        }
        out.push('\n');
    }
    out.push_str("];\n");

    let dest = Path::new(env!("CARGO_MANIFEST_DIR")).join("../embedded-smoke/src/mlp_policy.rs");
    std::fs::write(&dest, out).unwrap_or_else(|err| unreachable!("write {dest:?}: {err}"));
    println!("wrote {}", dest.display());
}
